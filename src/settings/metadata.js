export const SETTINGS_BY_KEY = new Map(SETTINGS.map((setting) => [setting.key, setting]));

export function groupedSettings() {
  const groups = [];
  const byName = new Map();
  for (const setting of SETTINGS) {
    if (!byName.has(setting.group)) {
      const group = { name: setting.group, settings: [] };
      byName.set(setting.group, group);
      groups.push(group);
    }
    byName.get(setting.group).settings.push(setting);
  }
  return groups;
}
