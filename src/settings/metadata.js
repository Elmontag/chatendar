function placeholderGroups(keys) {
  const allowed = new Set(keys);
  return PLACEHOLDER_CATALOG
    .map((group) => ({
      name: group.name,
      placeholders: group.placeholders.filter((placeholder) => allowed.has(placeholder.key)),
    }))
    .filter((group) => group.placeholders.length > 0);
}

